Product _desktopMacProduct({
  required String id,
  required String name,
  required String chip,
  required int year,
  required String tagline,
  required int basePrice,
  required List<String> storageOptions,
  required Map<String, int> storageDeltas,
  bool featured = false,
}) {
  const colors = <_ColorOption>[_ColorOption('Silver', Color(0xFFD9DADB))];
  final variants = <Variant>[];
  for (final color in colors) {
    for (final storage in storageOptions) {
      variants.add(
        Variant(
          id: '$id-${_slug(storage)}',
          colorName: color.name,
          color: color.color,
          storage: storage,
          price: basePrice + (storageDeltas[storage] ?? 0),
          stock: 8 + storage.hashCode.abs() % 6,
        ),
      );
    }
  }
  return Product(
    id: id,
    name: name,
    category: 'Mac',
    tagline: tagline,
    description:
        '$name with $chip — desktop power for creative and pro workflows.',
    detailedDescription:
        'Configure $name ($year) with $chip. Choose SSD capacity and connect Studio Display or Pro Display XDR.',
    basePrice: basePrice,
    specs: [
      chip,
      'Configurable SSD',
      'Thunderbolt',
      'macOS',
      'Wi‑Fi + Ethernet',
    ],
    keyFeatures: const [
      'Pro-level performance',
      'Configurable SSD',
      'Multiple Thunderbolt ports',
      'Runs macOS',
      'Whisper-quiet design',
    ],
    accent: const Color(0xFF7D8A95),
    icon: Icons.desktop_mac_outlined,
    imagePath: productImageFor(id),
    featured: featured,
    rating: 4.6 + (year % 7) * 0.04,
    reviewCount: 90 + year * 6,
    warranty: '1 Year Limited Warranty, AppleCare+ available',
    inStock: true,
    releaseDate: DateTime(year, 3, 10),
    reviews: _sampleReviews(name),
    variants: variants,
  );
}

